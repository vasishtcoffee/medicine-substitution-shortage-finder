"""Build the two standalone submission files from the real sources (so they can never drift):

  submission/01_DDL.sql   every DDL command: database, tables, ALTERs, views, functions, procedures, triggers, roles, grants
  submission/02_DML.sql   every DML command: seed INSERTs, INSERT/SELECT/UPDATE/DELETE demo, JOIN / nested / correlated /
                          recursive / CTE queries, procedure + function + trigger + sale demos

Run in the mysql client as root on an empty server:
  mysql -u root -p < submission/01_DDL.sql
  mysql -u root -p --force < submission/02_DML.sql      (--force: two statements are *expected* to fail, see comments)

Usage: python scripts/build_submission_sql.py
"""
import re

from argon2 import PasswordHasher

from envload import ROOT, env, load_env

load_env()
OUT = ROOT / "submission"
OUT.mkdir(exist_ok=True)
MIG = ROOT / "database" / "migrations"
SQL = ROOT / "database" / "sql"
DB = "medsub"


def clean(text: str) -> str:
    text = re.sub(r"DEFINER=\{\{DEFINER\}\}\s*", "", text)          # standalone: objects belong to whoever runs the file
    text = text.replace("{{DB}}", DB).replace("{{HOST}}", "%")
    return text.strip() + "\n"


def banner(title: str) -> str:
    return f"\n-- {'=' * 76}\n-- {title}\n-- {'=' * 76}\n"


def ddl() -> str:
    out = ["-- Medicine Substitution & Shortage Finder: ALL DDL (generated by scripts/build_submission_sql.py)",
           "-- Educational demonstration. Synthetic data only.",
           "-- Run on an empty MySQL 8 server as root:  mysql -u root -p < 01_DDL.sql",
           f"CREATE DATABASE IF NOT EXISTS {DB} CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;",
           f"USE {DB};",
           "SET GLOBAL log_bin_trust_function_creators = 1;  -- needed for functions/triggers when binary logging is on"]
    parts = [("1. TABLES (CREATE TABLE: PK, FK, UNIQUE, NOT NULL, CHECK, DEFAULT, ENUM, generated column)", "V001__core_schema.sql"),
             ("2. ALTER TABLE (added CHECKs, indexes, a new column)", "V002__alter_constraints.sql"),
             ("3. HELPER FUNCTIONS AND GUARD PROCEDURES (request context, availability band)", "R__10_context_and_guards.sql"),
             ("4. VIEWS (patient-safe availability, scoped stock views, substitution eligibility)", "R__20_views.sql"),
             ("5. TRIGGERS (low-stock alerts, order status machine)", "R__30_triggers.sql"),
             ("6. STORED PROCEDURES: substitution candidates", "R__40_candidates.sql"),
             ("7. STORED PROCEDURES: workflow, sale transaction, outbox, admin", "R__50_workflow.sql")]
    for title, f in parts:
        out.append(banner(title))
        out.append(clean((MIG / f).read_text(encoding="utf-8")))
    out.append(banner("8. ROLES AND GRANTS (MySQL has no native row-level security: roles + views + definer procedures)"))
    roles = "\n".join(f"CREATE ROLE IF NOT EXISTS '{r}'@'%';" for r in
                      ("app_patient_role", "app_pharmacist_role", "app_admin_role", "app_auth_role"))
    out.append(roles + "\n")
    out.append(clean((MIG / "R__90_grants.sql").read_text(encoding="utf-8")))
    return "\n".join(out)


def strip_markers(text: str) -> str:
    return text.strip() + "\n"


def dml() -> str:
    ph = PasswordHasher()
    users = [(1, "admin@medsub.demo", "Demo Admin", "admin", env("DEMO_ADMIN_PASSWORD")),
             (2, "pharmacist1@medsub.demo", "Demo Pharmacist One", "pharmacist", env("DEMO_PHARMACIST_PASSWORD")),
             (3, "pharmacist2@medsub.demo", "Demo Pharmacist Two", "pharmacist", env("DEMO_PHARMACIST_PASSWORD")),
             (4, "patient1@medsub.demo", "Demo Patient One", "patient", env("DEMO_PATIENT_PASSWORD")),
             (5, "patient2@medsub.demo", "Demo Patient Two", "patient", env("DEMO_PATIENT_PASSWORD"))]
    rows = ",\n".join(f"  ({i}, '{e}', '{n}', '{r}', '{ph.hash(p)}')" for i, e, n, r, p in users)
    out = ["-- Medicine Substitution & Shortage Finder: ALL DML (generated by scripts/build_submission_sql.py)",
           "-- Run AFTER 01_DDL.sql:  mysql -u root -p --force < 02_DML.sql",
           "-- Two statements in section 2 are EXPECTED to fail (CHECK violation, blocked FK delete); --force continues past them.",
           f"USE {DB};",
           banner("1. SEED DATA: INSERT ... ON DUPLICATE KEY UPDATE (idempotent). Demo logins' passwords are in .env (local only)"),
           "INSERT INTO users (id, email, full_name, role, password_hash) VALUES\n" + rows +
           "\nAS n ON DUPLICATE KEY UPDATE email = n.email, full_name = n.full_name, role = n.role, password_hash = n.password_hash;\n",
           strip_markers((ROOT / "database" / "seed" / "S001_seed.sql").read_text(encoding="utf-8")),
           "INSERT INTO pharmacist_assignments (user_id, pharmacy_id) VALUES (2, 1), (3, 2)\n"
           "AS n ON DUPLICATE KEY UPDATE pharmacy_id = n.pharmacy_id;\n",
           banner("2. DML DEMO: INSERT / SELECT / UPDATE / DELETE, a CHECK-blocked UPDATE, a blocked and a safe DELETE"),
           strip_markers((SQL / "dml_demo.sql").read_text(encoding="utf-8")),
           banner("3. QUERIES: JOIN, nested, correlated, recursive CTE, GROUP BY ... HAVING, LEFT JOIN aggregate"),
           strip_markers((SQL / "queries.sql").read_text(encoding="utf-8")),
           banner("4. ADVANCED: CTEs, function, procedures, trigger (needs a request context: set as admin below)"),
           "SET @app_user_id = 1, @app_role = 'admin', @app_pharmacy_id = NULL;\n",
           strip_markers((SQL / "advanced.sql").read_text(encoding="utf-8")),
           banner("5. SALE TRANSACTION DEMO: pharmacist of City Care completes approved order 3 (stock -2, ledger, outbox, status)"),
           "SET @app_user_id = 2, @app_role = 'pharmacist', @app_pharmacy_id = 1;\n"
           "SELECT quantity AS pyrelief_stock_before FROM inventory WHERE pharmacy_id = 1 AND medicine_id = 2;\n"
           "CALL sp_complete_order(3, 2);\n"
           "SELECT quantity AS pyrelief_stock_after FROM inventory WHERE pharmacy_id = 1 AND medicine_id = 2;\n"
           "SELECT id, movement_type, delta, order_id FROM inventory_movements WHERE order_id = 3;\n"
           "SELECT id, operation, entity_id, status FROM sync_outbox ORDER BY id DESC LIMIT 2;\n"
           "SELECT id, status FROM orders WHERE id = 3;\n"
           "-- calling it again must fail (status guard): CALL sp_complete_order(3, 2);   -> ERROR 45409\n"
           "SET @app_user_id = NULL, @app_role = NULL, @app_pharmacy_id = NULL;\n"]
    return "\n".join(out)


if __name__ == "__main__":
    (OUT / "01_DDL.sql").write_text(ddl(), encoding="utf-8")
    (OUT / "02_DML.sql").write_text(dml(), encoding="utf-8")
    print("wrote submission/01_DDL.sql and submission/02_DML.sql")
